import assert from 'node:assert/strict';
import { test } from 'node:test';
import { chromium } from 'playwright-core';
import { startM4Stack } from './m4-local-stack.mjs';

test('R07 teacher adopts an AI draft and explicitly publishes its student projection', { timeout: 180000 }, async (t) => {
  const stack = await startM4Stack(t, { appImports: ['./tests/r07-model-preload.mjs'] });
  const browser = await chromium.launch({ executablePath: process.env.M4_CHROME_PATH, headless: true });
  t.after(() => browser.close());
  const teacher = await browser.newPage({ viewport: { width: 390, height: 844 } });
  teacher.setDefaultTimeout(15000);
  const errors = [];
  teacher.on('pageerror', (error) => errors.push(error.message));
  const button = (name) => teacher.getByRole('button', { name, exact: true });
  const title = teacher.getByLabel('Title', { exact: true });
  const proposal = teacher.locator('#proposal-panel');
  const operations = [];
  teacher.on('request', (request) => {
    const url = new URL(request.url());
    if (request.method() === 'POST' && url.pathname === '/api/courses/') operations.push(url.searchParams.get('op'));
  });
  await teacher.goto(stack.base + '/enhancement-v2/studio/course/');
  await teacher.getByLabel('Email').fill(stack.accounts.teacher.email);
  await teacher.getByLabel('Password').fill(stack.accounts.teacher.password);
  await button('Sign in').click();
  await button('New draft').click();
  await teacher.locator('#cart-templates').waitFor();
  await teacher.getByLabel('Case for a new draft').selectOption('retry-queue');
  await teacher.getByText('retry-queue@1 · edge-cases').waitFor();
  assert.equal(await teacher.locator('#cart-templates').isVisible(), false);
  assert.equal(await teacher.getByText('Optional Mock examples for the checkout case.').isVisible(), false);

  await teacher.getByLabel('Course topic').fill('Trace retries near the delay cap');
  await teacher.getByLabel('Learning objective', { exact: true }).fill('Explain how the delay cap affects a retry.');
  await teacher.locator('[data-field="requirementId"]').selectOption('backoff-cap');
  await teacher.getByLabel('Teaching constraints').fill('Use a concrete trace.');
  await title.fill('My unsaved teaching material');
  await button('Generate draft with AI').click();
  await proposal.waitFor();
  assert.match(await proposal.innerText(), /Trace the retry backoff cap/);
  assert.match(await proposal.innerText(), /Private rubric:/);
  assert.equal(await title.inputValue(), 'My unsaved teaching material');
  assert.equal(operations.includes('save'), false);
  await button('Discard').click();
  await proposal.waitFor({ state: 'hidden' });
  assert.equal(await title.inputValue(), 'My unsaved teaching material');

  await button('Generate draft with AI').click();
  await proposal.waitFor();
  assert.equal(await teacher.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  teacher.once('dialog', (dialog) => dialog.accept());
  await button('Accept').click();
  assert.equal(await title.inputValue(), 'Trace the retry backoff cap');
  assert.equal(await button('Review saved revision').isDisabled(), true);
  assert.equal(await button('Publish new version').isDisabled(), true);
  assert.equal(operations.includes('save'), false);
  await title.fill('Teacher-edited retry lesson');

  await button('Preview current form').click();
  await teacher.locator('#preview-panel').waitFor();
  assert.doesNotMatch(await teacher.locator('#preview-panel').innerText(), /Private rubric|Teacher-only answer guidance/);
  await button('Save draft').click();
  await teacher.getByText('Saved revision 1.', { exact: true }).waitFor();
  assert.equal(await button('Publish new version').isDisabled(), true);
  await button('Reopen draft').click();
  await teacher.getByText('Opened Teacher-edited retry lesson.').waitFor();
  assert.equal(await teacher.locator('#material-source').innerText(), 'Source · AI-assisted');

  const constraints = teacher.getByLabel('Teaching constraints');
  await constraints.fill('Fixture: provider failure');
  await button('Generate draft with AI').click();
  await teacher.locator('#ai-status').getByText('The AI service could not complete the request. Try again.').waitFor();
  assert.equal(await title.inputValue(), 'Teacher-edited retry lesson');
  assert.equal(await constraints.inputValue(), 'Fixture: provider failure');
  assert.equal(await proposal.isVisible(), false);
  assert.equal(operations.filter((op) => op === 'save').length, 1);
  teacher.once('dialog', (dialog) => dialog.accept());
  await button('Reopen draft').click();
  await teacher.getByText('Opened Teacher-edited retry lesson.').waitFor();
  assert.equal(await constraints.inputValue(), 'Use a concrete trace.');

  await button('Review saved revision').click();
  await teacher.getByRole('heading', { name: 'Review revision 1 · Teacher-edited retry lesson' }).waitFor();
  assert.equal(await button('Publish new version').isDisabled(), true);
  await teacher.getByLabel('I checked the requirements', { exact: false }).check();
  await button('Approve this revision').click();
  await teacher.getByText('Approved revision 1.', { exact: false }).waitFor();
  teacher.once('dialog', (dialog) => dialog.accept());
  await button('Publish new version').click();
  const link = teacher.getByRole('link', { name: 'Version 1 · Teacher-edited retry lesson' });
  await link.waitFor();
  const learner = await browser.newPage();
  const learnerUrl = new URL(await link.getAttribute('href'));
  await learner.goto(learnerUrl.href);
  await learner.getByRole('heading', { name: 'Teacher-edited retry lesson', exact: true }).waitFor();
  assert.doesNotMatch(await learner.locator('main').innerText(), /Private rubric|Teacher-only answer guidance/);
  const publicJson = await fetch(stack.base + '/api/courses/?op=published&' + learnerUrl.searchParams);
  assert.equal(publicJson.status, 200);
  assert.doesNotMatch(await publicJson.text(), /Private rubric|teacherAnswerGuidance|provenance|receipt/);
  assert.deepEqual(errors, []);
});
